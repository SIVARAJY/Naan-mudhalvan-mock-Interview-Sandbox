def _course_progress(uid, course_id, conn):
    """Returns (completed_lessons, total_lessons, pct) for a user in a course."""
    total = conn.execute(
        "SELECT COUNT(*) AS c FROM lh_lessons WHERE course_id = %s", (course_id,)
    ).fetchone()["c"]
    if total == 0:
        return 0, 0, 0
    done = conn.execute("""
        SELECT COUNT(*) AS c FROM lh_lesson_progress lp
        JOIN lh_lessons l ON l.id = lp.lesson_id
        WHERE lp.user_id = %s AND l.course_id = %s AND lp.completed = TRUE
    """, (uid, course_id)).fetchone()["c"]
    pct = round(done / total * 100)
    return done, total, pct

