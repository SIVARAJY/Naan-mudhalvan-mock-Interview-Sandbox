@app.route("/learning/api/quiz", methods=["POST"])
@login_required
def submit_quiz():
    uid = session["user"]["id"]
    data = request.get_json(force=True)
    lesson_id = int(data.get("lesson_id", 0))
    answers = data.get("answers", {})  # {question_index: chosen_index}
    if not lesson_id:
        return jsonify({"ok": False}), 400
    with get_db() as conn:
        lesson = conn.execute("SELECT quiz_data FROM lh_lessons WHERE id=%s", (lesson_id,)).fetchone()
        if not lesson:
            return jsonify({"ok": False}), 404
        quiz = json.loads(lesson["quiz_data"]) if isinstance(lesson["quiz_data"], str) else lesson["quiz_data"]
        if not quiz:
            return jsonify({"ok": True, "score": 100, "correct": 0, "total": 0, "results": []})

        results = []
        correct = 0
        for i, q in enumerate(quiz):
            chosen = answers.get(str(i))
            is_correct = chosen is not None and int(chosen) == int(q["answer"])
            if is_correct:
                correct += 1
            results.append({"correct": is_correct, "answer": q["answer"]})

        score = round(correct / len(quiz) * 100, 1)
        conn.execute("""
            INSERT INTO lh_quiz_attempts (user_id, lesson_id, score, answers)
            VALUES (%s,%s,%s,%s)
        """, (uid, lesson_id, score, json.dumps(answers)))

        # Auto-complete lesson if quiz passed (>= 60%)
        if score >= 60:
            conn.execute("""
                INSERT INTO lh_lesson_progress (user_id, lesson_id, completed, last_watched)
                VALUES (%s,%s,TRUE,NOW())
                ON CONFLICT (user_id, lesson_id) DO UPDATE SET completed=TRUE, last_watched=NOW()
            """, (uid, lesson_id))
            # Check course completion
            l_row = conn.execute("SELECT course_id FROM lh_lessons WHERE id=%s", (lesson_id,)).fetchone()
            if l_row:
                done, total, pct = _course_progress(uid, l_row["course_id"], conn)
                if pct == 100:
                    conn.execute("""
                        UPDATE lh_enrollments SET completed=TRUE, cert_issued=TRUE
                        WHERE user_id=%s AND course_id=%s
                    """, (uid, l_row["course_id"]))

    return jsonify({"ok": True, "score": score, "correct": correct,
                    "total": len(quiz), "results": results})

