@app.route("/admin/learning/course/<int:course_id>/add-lesson", methods=["GET", "POST"])
@_admin_required
def admin_add_lesson(course_id):
    with get_db() as conn:
        course = conn.execute("SELECT * FROM lh_courses WHERE id=%s", (course_id,)).fetchone()
        if not course:
            abort(404)
        if request.method == "POST":
            title       = request.form.get("title", "").strip()
            youtube_url = request.form.get("youtube_url", "").strip()
            duration    = int(request.form.get("duration_min", 0) or 0)
            video_id    = _extract_yt_id(youtube_url)
            if not title or not video_id:
                flash("Title and a valid YouTube URL are required.", "error")
                return redirect(url_for("admin_add_lesson", course_id=course_id))

            # Parse quiz questions from form (up to 5)
            quiz = []
            for qi in range(1, 6):
                q_text = request.form.get(f"q{qi}", "").strip()
                if not q_text:
                    break
                opts = [request.form.get(f"q{qi}_o{oi}", "").strip() for oi in range(1, 5)]
                opts = [o for o in opts if o]
                ans  = int(request.form.get(f"q{qi}_ans", 0) or 0)
                if opts:
                    quiz.append({"q": q_text, "options": opts, "answer": ans})

            # Auto-compute lesson order
            max_order = conn.execute(
                "SELECT COALESCE(MAX(lesson_order),0) AS m FROM lh_lessons WHERE course_id=%s",
                (course_id,)
            ).fetchone()["m"]
            conn.execute("""
                INSERT INTO lh_lessons (course_id, title, youtube_url, video_id, duration_min, lesson_order, quiz_data)
                VALUES (%s,%s,%s,%s,%s,%s,%s)
            """, (course_id, title, youtube_url, video_id, duration,
                  max_order + 1, json.dumps(quiz)))
            flash(f"Lesson '{title}' added.", "info")
            return redirect(url_for("admin_add_lesson", course_id=course_id))

        lessons = conn.execute(
            "SELECT * FROM lh_lessons WHERE course_id=%s ORDER BY lesson_order", (course_id,)
        ).fetchall()
    return render_template("admin_add_lesson.html", course=course, lessons=lessons)

