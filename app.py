def _supabase_auth(path, payload, method="POST", bearer=None):
    """Call Supabase Auth. Returns (data, error_message)."""
    if not SUPABASE_URL or not SUPABASE_ANON_KEY:
        return None, "Login is not configured. Set SUPABASE_URL and SUPABASE_ANON_KEY."
    headers = {"apikey": SUPABASE_ANON_KEY, "Content-Type": "application/json"}
    if bearer:
        headers["Authorization"] = f"Bearer {bearer}"
    try:
        resp = requests.request(
            method, f"{SUPABASE_URL}/auth/v1/{path}",
            headers=headers, json=payload, timeout=10,
        )
        data = resp.json()
    except (requests.RequestException, ValueError):
        return None, "Could not reach the sign-in service. Please try again."
    if resp.status_code >= 400:
        code = data.get("error_code") or data.get("code")
        return None, AUTH_ERRORS.get(code) or data.get("msg") or data.get("message") or "Sign-in failed."
    return data, None

@app.route("/login")
def login():
    if "user" in session:
        return redirect(url_for("dashboard"))
    mode = "signup" if request.args.get("mode") == "signup" else "signin"
    return render_template("login.html", mode=mode, csrf=_csrf_token())

@app.route("/auth/signin", methods=["POST"])
def auth_signin():
    _check_csrf()
    email = request.form.get("email", "").strip().lower()
    password = request.form.get("password", "")
    if not email or not password:
        flash("Enter your email and password.", "error")
        return redirect(url_for("login"))
    data, err = _supabase_auth("token?grant_type=password", {"email": email, "password": password})
    if err or not data or "user" not in data:
        flash(err or "Sign-in failed.", "error")
        return redirect(url_for("login"))
    _start_session(data["user"])
    return redirect(url_for("dashboard"))

@app.route("/auth/signup", methods=["POST"])
def auth_signup():
    _check_csrf()
    name = request.form.get("name", "").strip()
    email = request.form.get("email", "").strip().lower()
    password = request.form.get("password", "")
    confirm = request.form.get("confirm", "")
    back = url_for("login", mode="signup")
    if not name or not email or "@" not in email:
        flash("Enter your name and a valid email address.", "error")
        return redirect(back)
    if len(password) < 8:
        flash("Password must be at least 8 characters.", "error")
        return redirect(back)
    if password != confirm:
        flash("The two passwords do not match.", "error")
        return redirect(back)
    data, err = _supabase_auth("signup", {
        "email": email, "password": password, "data": {"full_name": name},
    })
    if err:
        flash(err, "error")
        return redirect(back)
    if data.get("access_token") and data.get("user"):
        # Email confirmation is switched off in Supabase: sign in straight away.
        _start_session(data["user"])
        return redirect(url_for("dashboard"))
    flash("Account created. Check your email for a confirmation link, then sign in.", "info")
    return redirect(url_for("login"))

@app.route("/forgot", methods=["GET", "POST"])
def forgot():
    if request.method == "GET":
        return render_template("login.html", mode="forgot", csrf=_csrf_token())
    _check_csrf()
    email = request.form.get("email", "").strip().lower()
    if not email or "@" not in email:
        flash("Enter the email address you registered with.", "error")
        return redirect(url_for("forgot"))
    verifier, challenge = _pkce_pair()
    session["reset_verifier"] = verifier
    callback = url_for("reset_callback", _external=True)
    data, err = _supabase_auth(
        f"recover?redirect_to={requests.utils.quote(callback, safe='')}",
        {"email": email, "code_challenge": challenge, "code_challenge_method": "s256"},
    )
    if err:
        flash(err, "error")
        return redirect(url_for("forgot"))
    # Same message whether or not the email has an account (avoids revealing who is registered).
    flash("If an account exists for that email, a reset link has been sent. "
          "Open the link in this same browser.", "info")
    return redirect(url_for("login"))

@app.route("/auth/reset-callback")
def reset_callback():
    """The emailed link lands here with ?code=... ; trade it for a short-lived reset token."""
    code = request.args.get("code")
    verifier = session.pop("reset_verifier", None)
    if not code or not verifier:
        flash("That reset link is invalid or has expired. Request a new one "
              "and open it in the same browser.", "error")
        return redirect(url_for("forgot"))
    data, err = _supabase_auth("token?grant_type=pkce",
                               {"auth_code": code, "code_verifier": verifier})
    if err or not data or not data.get("access_token"):
        flash("That reset link is invalid or has expired. Request a new one.", "error")
        return redirect(url_for("forgot"))
    session["reset_token"] = data["access_token"]   # lets the student set a password; not a login
    return redirect(url_for("reset_password"))

@app.route("/reset-password", methods=["GET", "POST"])
def reset_password():
    token = session.get("reset_token")
    if not token:
        flash("Start by requesting a password reset link.", "error")
        return redirect(url_for("forgot"))
    if request.method == "GET":
        return render_template("login.html", mode="reset", csrf=_csrf_token())
    _check_csrf()
    password = request.form.get("password", "")
    confirm = request.form.get("confirm", "")
    if len(password) < 8:
        flash("Password must be at least 8 characters.", "error")
        return redirect(url_for("reset_password"))
    if password != confirm:
        flash("The two passwords do not match.", "error")
        return redirect(url_for("reset_password"))
    data, err = _supabase_auth("user", {"password": password}, method="PUT", bearer=token)
    if err:
        flash(err, "error")
        return redirect(url_for("reset_password"))
    session.pop("reset_token", None)
    flash("Password updated. Please sign in with your new password.", "info")
    return redirect(url_for("login"))

@app.route("/auth/google")
def auth_google():
    """Send the student to Google (through Supabase) using the PKCE flow."""
    if not SUPABASE_URL or not SUPABASE_ANON_KEY:
        flash("Login is not configured. Set SUPABASE_URL and SUPABASE_ANON_KEY.")
        return redirect(url_for("login"))
    verifier, challenge = _pkce_pair()
    session["pkce_verifier"] = verifier
    callback = url_for("auth_callback", _external=True)
    authorize_url = (
        f"{SUPABASE_URL}/auth/v1/authorize?provider=google"
        f"&redirect_to={requests.utils.quote(callback, safe='')}"
        f"&code_challenge={challenge}&code_challenge_method=s256"
    )
    return redirect(authorize_url)

@app.route("/auth/callback")
def auth_callback():
    """Supabase sends the student back here with ?code=... ; we exchange it for a verified user."""
    if request.args.get("error"):
        flash("Google sign-in was cancelled or failed. Please try again.")
        return redirect(url_for("login"))
    code = request.args.get("code")
    verifier = session.pop("pkce_verifier", None)
    if not code or not verifier:
        flash("Sign-in session expired. Please click Continue with Google again.")
        return redirect(url_for("login"))
    try:
        resp = requests.post(
            f"{SUPABASE_URL}/auth/v1/token?grant_type=pkce",
            headers={"apikey": SUPABASE_ANON_KEY, "Content-Type": "application/json"},
            json={"auth_code": code, "code_verifier": verifier},
            timeout=10,
        )
        resp.raise_for_status()
        data = resp.json()
        user = data["user"]
    except (requests.RequestException, KeyError, ValueError):
        flash("Could not complete sign-in with Supabase. Please try again.")
        return redirect(url_for("login"))

    _start_session(user)
    return redirect(url_for("dashboard"))

