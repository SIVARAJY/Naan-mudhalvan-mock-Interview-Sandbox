@contextmanager
def get_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is missing. Create a .env file using .env.example.")
    conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, sslmode="require")
    try:
        with conn:
            yield conn
    finally:
        conn.close()

