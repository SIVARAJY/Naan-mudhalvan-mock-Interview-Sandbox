            quiz = []
            for qi in range(1, 6):
                q_text = request.form.get(f"q{qi}", "").strip()
                if not q_text:
                    break
                opts = [request.form.get(f"q{qi}_o{oi}", "").strip() for oi in range(1, 5)]
