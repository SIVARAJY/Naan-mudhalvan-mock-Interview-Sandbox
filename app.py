CHALLENGE = {
    "title": "Find the maximum",
    "description": "Write a function that returns the largest number in a non-empty list.",
    "example": "Input: [3, 9, 2]  ->  Output: 9",
    "starter": "def find_max(numbers):\n    # Write your solution here\n    pass",
    "hints": "Consider using max(numbers) or comparing values in a loop.",
}

@contextmanager
def get_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is missing. Create a .env file using .env.example.")
    conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, sslmode="require")
    try:
        with conn:
            yield conn
    finally:
        conn.close()

def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS attempts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_name TEXT NOT NULL,
                attempt_type TEXT NOT NULL,
                topic TEXT NOT NULL,
                score DOUBLE PRECISION NOT NULL CHECK (score >= 0 AND score <= 100),
                feedback TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

def save_attempt(student_name, attempt_type, topic, score, feedback):
    with get_db() as conn:
        conn.execute(
            """INSERT INTO attempts (student_name, attempt_type, topic, score, feedback, created_at)
               VALUES (%s, %s, %s, %s, %s, %s)""",
            (student_name, attempt_type, topic, score, feedback, datetime.now().astimezone())
        )

@app.route("/")
def dashboard():
    with get_db() as conn:
        attempts = conn.execute("SELECT * FROM attempts ORDER BY id DESC LIMIT 8").fetchall()
        summary = conn.execute("""
            SELECT COUNT(*) AS count, COALESCE(AVG(score), 0) AS average FROM attempts
        """).fetchone()
    return render_template("dashboard.html", attempts=attempts, summary=summary)

@app.route("/interview", methods=["GET", "POST"])
def interview():
    if request.method == "POST":
        student_name = request.form.get("student_name", "").strip() or "Demo Student"
        correct = sum(
            request.form.get(f"q{q['id']}", "").strip().lower() == q["answer"].lower()
            for q in QUESTIONS
        )
        total = len(QUESTIONS)
        missed_topics = [
            q["topic"] for q in QUESTIONS
            if request.form.get(f"q{q['id']}", "").strip().lower() != q["answer"].lower()
        ]
        correctness = correct / total * 100
        completion = 100
        reflection = 100 if request.form.get("reflection", "").strip() else 50
        final_score = round(0.70 * correctness + 0.20 * completion + 0.10 * reflection, 1)
        feedback = f"{correct}/{total} answers correct. Review: {', '.join(missed_topics) if missed_topics else 'No weak topics detected in this attempt'}."
        save_attempt(student_name, "Mock Interview", "Mixed Technical", final_score, feedback)
        return render_template("interview_result.html", student_name=student_name, correct=correct,
            total=total, correctness=round(correctness, 1), completion=completion, reflection=reflection,
            final_score=final_score, feedback=feedback, questions=QUESTIONS, submitted=request.form)
    return render_template("interview.html", questions=QUESTIONS)

@app.route("/coding", methods=["GET", "POST"])
def coding():
    if request.method == "POST":
        student_name = request.form.get("student_name", "").strip() or "Demo Student"
        code = request.form.get("code", "")
        checks = {
            "Defines a function": "def " in code,
            "Returns a result": "return" in code,
            "Uses a max/comparison approach": ("max(" in code or ">" in code or "sorted(" in code),
        }
        score = round(sum(checks.values()) / len(checks) * 100, 1)
        feedback = "Static rubric checks: " + ", ".join(
            f"{label}: {'pass' if ok else 'review'}" for label, ok in checks.items()
        )
        save_attempt(student_name, "Coding Sandbox", CHALLENGE["title"], score, feedback)
        return render_template("coding_result.html", student_name=student_name, score=score,
                               checks=checks, feedback=feedback)
    return render_template("coding.html", challenge=CHALLENGE)

@app.route("/history")
def history():
    with get_db() as conn:
        attempts = conn.execute("SELECT * FROM attempts ORDER BY id DESC").fetchall()
    return render_template("history.html", attempts=attempts)

